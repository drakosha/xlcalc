/** A signature read: its groups of arguments in order (an optional group in brackets), and whether the last group repeats. */
interface Shape {
  groups: { optional: boolean; names: string[] }[]
  repeats: boolean
}

const SHAPES = new Map<string, Shape>()

/** A function's signature as `SIGNATURES` writes it, read once. */
function shapeOf(name: string): Shape {
  let shape = SHAPES.get(name)
  if (shape) return shape
  shape = { groups: [], repeats: false }
  let open: Shape['groups'][number] | null = null
  for (const t of SIGNATURES[name].split(' ').filter(Boolean)) {
    if (t === '...') {
      shape.repeats = true
      continue
    }
    const word = t.replace(/^\[|\]$/g, '')
    if (!open) shape.groups.push((open = { optional: t.startsWith('['), names: [] }))
    open.names.push(word)
    if (!open.optional || t.endsWith(']')) open = null
  }
  SHAPES.set(name, shape)
  return shape
}

/** An argument's name in the locale: its word translated, its number kept (`number1`, `число1`). */
function translated(name: string, words: Readonly<Record<string, string>> | undefined): string {
  const [, word, n] = /^(.*?)(\d*)$/.exec(name)!
  return (words?.[word] ?? word) + n
}

/**
 * The signature of a function, by its name in English or in the locale (any case), for a tip of its arguments while a
 * formula is typed; null for a name that is no function of the whitelist.
 */
export function functionSignature(name: string, locale?: string | Locale): FunctionSignature | null {
  checkString(name, 'name')
  const loc = locale === undefined ? localeOf(undefined) : checkLocaleArg(locale, 'locale')
  const upper = name.toUpperCase()
  const invariant = upper in SIGNATURES ? upper : Object.keys(loc.functions).find((k) => loc.functions[k].toUpperCase() === upper)
  if (!invariant || !(invariant in SIGNATURES)) return null
  const shape = shapeOf(invariant)
  const words = loc.argumentWords
  const groups = shape.groups.map((g) => ({ optional: g.optional, names: g.names.map((n) => translated(n, words)) }))
  const sep = loc.listSeparator === ',' ? ', ' : loc.listSeparator
  const parts = groups.map((g) => (g.optional ? `[${g.names.join(sep)}]` : g.names.join(sep)))
  const local = loc.functions[invariant] ?? invariant
  const args: FunctionArgument[] = groups.flatMap((g) => g.names.map((n) => ({ name: n, optional: g.optional })))
  const category = CATEGORY_OF.get(invariant)!
  const own = loc.functionText
  return {
    name: local,
    fn: invariant,
    args,
    repeat: shape.repeats ? groups[groups.length - 1].names.length : 0,
    text: `${local}(${[...parts, ...(shape.repeats ? ['...'] : [])].join(sep)})`,
    category,
    categoryName: own?.categories[category] ?? CATEGORY_NAMES[category],
  }
}
