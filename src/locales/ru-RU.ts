function plural(n: number, one: string, few: string, many: string): string {
  const [tens, units] = [n % 100, n % 10]
  return tens >= 11 && tens <= 14 ? many : units === 1 ? one : units >= 2 && units <= 4 ? few : many
}

const q = (s: string) => `«${s}»`
const and = (xs: string[]) => (xs.length < 2 ? xs.map(q).join('') : `${xs.slice(0, -1).map(q).join(', ')} и ${q(xs.at(-1)!)}`)
const lower = (s: string) => s[0].toLowerCase() + s.slice(1)
const upper = (s: string) => s[0].toUpperCase() + s.slice(1)

/** Rows or columns after a number, as `вставить 2 строки` takes them. */
const lines = (n: number, l: Lines) => `${n} ${l === 'rows' ? plural(n, 'строку', 'строки', 'строк') : plural(n, 'столбец', 'столбца', 'столбцов')}`
/** Rows or columns, as `вставка строк` takes them. */
const ofLines = (l: Lines) => (l === 'rows' ? 'строк' : 'столбцов')

const FOUND = { num: 'число', str: 'текст', err: 'значение ошибки', ref: 'ссылка', table: 'ссылка на таблицу', eof: 'конец формулы' }

/** What the parser found, in the locale's words; `arr`: inside an array constant, where `,` is the column separator. */
function found(f: Found, w: Words, arr = false): string {
  switch (f.t) {
    case 'op':
      return f.v === ' ' ? 'пробел' : q(f.v)
    case 'ident': {
      const up = f.v.toUpperCase()
      return q(up === 'TRUE' || up === 'FALSE' ? w.loc.booleans[up] : f.v)
    }
    case 'fn':
      return q(w.fn(f.v))
    case ',':
      return q(arr ? w.loc.arrayColumnSeparator : w.loc.listSeparator)
    case ';':
      return q(w.loc.arrayRowSeparator)
    case '(':
    case ')':
    case '{':
    case '}':
      return q(f.t)
    default:
      return FOUND[f.t]
  }
}

/** What stands where something else was expected: `а здесь число`, or the end of the formula. */
const instead = (f: Found, w: Words, arr = false) => (f.t === 'eof' ? 'а формула закончилась' : `а здесь ${found(f, w, arr)}`)

function counts({ min, max, parity, or }: Counts): string {
  const args = (n: number) => `${n} ${plural(n, 'аргумент', 'аргумента', 'аргументов')}`
  if (!parity) return min === max ? args(min) : `от ${min} до ${max} ${plural(max, 'аргумента', 'аргументов', 'аргументов')}`
  const kind = parity === 'odd' ? 'нечётное' : 'чётное'
  return or ? `${args(min)} или ${kind} число от ${min + 1} до ${max}` : `${kind} число аргументов от ${min} до ${max}`
}

