const NAME = { error: 'NAME' } as const

/** What the calls read: two columns beside the formula. */
const CELLS = Object.fromEntries([1, 2, 3, 4].flatMap((r, i) => [[`B${r}`, { value: i + 1 }], [`C${r}`, { value: [2, 3, 5, 7][i] }]]))

const CALCULATE = new Set(['NETWORKDAYS.INTL', 'WORKDAY.INTL'])

function one(id: string, about: string, formula: string, predicted?: CachedValue): LinksCase {
  return {
    id,
    about,
    sheets: [{ name: 'S', cells: CELLS }],
    linked: { S: { A1: formula } },
    links: [],
    read: [{ sheet: 'S', range: 'A1' }],
    ...(predicted === undefined ? {} : { predicted: { 'S!A1': predicted } }),
  }
}

/** The file name of a case: a function's name without its dots. */
const idOf = (fn: string) => fn.replaceAll('.', '-')

export function buildLinksCases(): LinksCases {
  const names = [...XLFN, ...XLWS].sort()
  const missing = names.filter((n) => !CALLS[n])
  if (missing.length) throw new Error(`no-prefix: no call of ${missing.join(', ')}`)
  return {
    cases: [
      ...names.map((n) => one(idOf(n), `${n} without its prefix`, CALLS[n], CALCULATE.has(n) || XLWS.has(n) ? undefined : NAME)),
      one('with-prefix', 'the same call with its prefix', '_xlfn.XLOOKUP(2,{1,2},{3,4})', 4),
      one('old-function', 'a function of Excel 2007', 'SUM(B1:B4)', 10),
      one('lower-case', 'a name in lower case', 'xlookup(2,{1,2},{3,4})', NAME),
      one('nested', 'inside a function of Excel 2007', 'SUM(1,XLOOKUP(2,{1,2},{3,4}))', NAME),
      one('in-iferror', 'inside IFERROR, as an agent wrote one', 'IFERROR(AGGREGATE(9,6,B1:B4),"none")', 'none'),
      one('in-text', 'a name in quotes only', '"XLOOKUP(1)"', 'XLOOKUP(1)'),
      one('old-and-new', 'a newer function with its prefix beside one without', '_xlfn.IFNA(1,2)+DAYS(10,1)', NAME),
    ],
  }
}
