/** A file with TEXT of a value by a code, read as Excel computes it. */
export const textCase = (id: string, code: string, predicted: string | null, value = '46096.5'): LinksCase => {
  const answer: CachedValue = predicted === null ? { error: 'VALUE' } : predicted
  return {
    id,
    about: `TEXT(${value}) with ${code}`,
    sheets: [{ name: 'S', cells: { B1: { value: 1 } } }],
    linked: { S: { A1: `TEXT(${value},"${code.replaceAll('"', '""')}")` } },
    links: [],
    read: [{ sheet: 'S', range: 'A1' }],
    predicted: { 'S!A1': answer },
  }
}

export function buildLinksCases(): LinksCases {
  return { cases: HELD.map(([code, text, value], i) => textCase(`h${i + 1}`, code, text, value)) }
}
