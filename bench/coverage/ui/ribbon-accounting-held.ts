export function buildUiCases(): UiCase[] {
  const { out, add } = collector()
  const cells = Object.fromEntries([...DECIMALS, ...THREE, ...OTHER].map((numberFormat, i) => [`B${i + 1}`, { value: -1234.5, numberFormat }]))
  add('held', { cells, act: { do: 'ribbon', cells: Object.keys(cells) } })
  return out
}
