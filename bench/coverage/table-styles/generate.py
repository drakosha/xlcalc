#!/usr/bin/env python3
"""Generate the optional preset data from the ECMA-376 SpreadsheetMLStyles archive."""
import hashlib
import json
import sys
from pathlib import Path
from xml.etree import ElementTree as ET
from zipfile import ZipFile


def local(tag):
    return tag.rsplit("}", 1)[-1]


def xml_without_namespaces(element):
    for node in element.iter():
        node.tag = local(node.tag)
        node.attrib = {local(key): value for key, value in node.attrib.items()}
        node.text = node.text if node.text and node.text.strip() else None
        node.tail = None
    return ET.tostring(element, encoding="unicode", short_empty_elements=True)


archive = Path(sys.argv[1])
output = Path(sys.argv[2])
with ZipFile(archive) as source:
    raw = source.read("presetTableStyles.xml")

dxfs = {}
presets = {}
for preset in ET.fromstring(raw):
    name = local(preset.tag)
    formats, table_styles = preset
    assert local(formats.tag) == "dxfs" and local(table_styles.tag) == "tableStyles", name
    style, = table_styles
    # Two nested names have extra suffixes. The containing element names the preset.
    source_names = {"TableStyleLight14": "TableStyleLight14 ", "TableStyleDark9": "TableStyleDark9 2"}
    assert style.attrib["name"] == source_names.get(name, name), name
    positions = []
    for fmt in formats:
        xml = xml_without_namespaces(fmt)
        positions.append(dxfs.setdefault(xml, len(dxfs)))
    raw_ids = [int(region.attrib["dxfId"]) for region in style]
    # The source uses one-based indices in the table presets and zero-based in the pivot presets.
    table = name.startswith("TableStyle")
    assert not table or max(raw_ids) == len(positions), name
    assert table or min(raw_ids) == 0, name
    offset = int(table)
    regions = []
    for region, raw_id in zip(style, raw_ids):
        index = raw_id - offset
        assert 0 <= index < len(positions), (name, index)
        regions.append([region.attrib["type"], int(region.attrib.get("size", "1")), positions[index]])
    presets[name] = regions

encode = lambda value: json.dumps(value, ensure_ascii=False, separators=(",", ":"))
lines = [
    "// Generated by bench/coverage/table-styles/generate.py from ECMA-376 presetTableStyles.xml.",
    f"// Source SHA-256: {hashlib.sha256(raw).hexdigest()}",
    "",
    "/** A style region, its stripe size, and its index in the differential formats. */",
    "export type PresetStyleElement = readonly [type: string, size: number, differentialFormat: number]",
    "",
    "/** ECMA-376 differential formats in SpreadsheetML, shared by the presets. */",
    "export const PRESET_DIFFERENTIAL_FORMATS: readonly string[] = [",
    *(f"  {encode(xml)}," for xml in dxfs),
    "]",
    "",
    "/** The ECMA-376 built-in style regions by style name. */",
    "export const PRESET_TABLE_STYLES: Readonly<Record<string, readonly PresetStyleElement[]>> = {",
    *(f"  {name}: {encode(regions)}," for name, regions in presets.items()),
    "}",
    "",
]
output.write_text("\n".join(lines), encoding="utf-8")
print(f"{len(presets)} presets, {len(dxfs)} unique differential formats, {output.stat().st_size} source bytes")
