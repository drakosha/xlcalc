/**
 * Writes the locale file `src/locale/<tag>.ts` from Excel's snapshot (`test/excel/locale/<tag>.json`):
 *
 *   npx tsx bench/locale/generate.ts ru
 *
 * The file holds the function names that differ from the English ones; `test/locale-excel.test.ts` checks
 * that it equals what the snapshot gives.
 */
import { writeFileSync } from 'node:fs'
import { derive, loadSnapshot, type Derived } from './derive.js'

const TAGS: Record<string, { tag: string; name: string }> = { ru: { tag: 'ru-RU', name: 'ruRU' } }

/**
 * The specifiers of structured references, which the snapshot's books have none of: as Excel 16.113 ru-RU shows them
 * (`#Все`, `#Данные`, `#Заголовки`, `#Итоги`) and takes them typed (`#Эта строка`, shown as `@`); the table set
 * `locale` checks them (`test/excel/tables/ru-RU/locale.json`).
 */
const TABLE_ITEMS: Record<string, Record<string, string>> = { 'ru-RU': { '#All': '#Все', '#Data': '#Данные', '#Headers': '#Заголовки', '#Totals': '#Итоги', '#This Row': '#Эта строка' } }

/** `key: 'value'` entries packed into lines of at most `width` characters. */
function pack(entries: [string, string][], indent: string, width = 120): string {
  const lines: string[] = []
  let line = ''
  for (const [k, v] of entries) {
    const item = `${/^[A-Z][A-Z0-9]*$/.test(k) ? k : `'${k}'`}: '${v}',`
    if (line && indent.length + line.length + 1 + item.length > width) {
      lines.push(indent + line)
      line = item
    } else line = line ? `${line} ${item}` : item
  }
  if (line) lines.push(indent + line)
  return lines.join('\n')
}

/** The locale's source text: data only. */
function localeSource(tag: string, name: string, d: Derived, excel: string): string {
  const differ = Object.entries(d.functions).filter(([en, l]) => en !== l).sort(([a], [b]) => (a < b ? -1 : 1))
  const errors = Object.entries(d.errors).filter(([en, l]) => en !== l)
  const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  return `/**
 * ${tag}: Excel ${excel} for Mac with the ${tag === 'ru-RU' ? 'Russian' : tag} interface and locale. Generated by
 * \`bench/locale/generate.ts\` from Excel's own formula text (\`test/excel/locale/${tag}.json\`); do not edit.
 * Functions whose name is the English one are not listed.
 */
import type { Locale } from './types.js'

export const ${name}: Locale = {
  tag: '${tag}',
  decimalSeparator: ${q(d.decimalSeparator)},
  listSeparator: ${q(d.listSeparator)},
  arrayColumnSeparator: ${q(d.arrayColumnSeparator)},
  arrayRowSeparator: ${q(d.arrayRowSeparator)},
  booleans: { TRUE: ${q(d.booleans.TRUE)}, FALSE: ${q(d.booleans.FALSE)} },
  errors: {
${pack(errors, '    ')}
  },
  functions: {
${pack(differ, '    ')}
  },${TABLE_ITEMS[tag] ? `\n  tableItems: { ${Object.entries(TABLE_ITEMS[tag]).map(([k, v]) => `${q(k)}: ${q(v)}`).join(', ')} },` : ''}
}
`
}

const arg = process.argv[2] ?? 'ru'
const t = TAGS[arg]
if (!t) throw new Error(`locale: ${Object.keys(TAGS).join(' | ')}`)
const snap = loadSnapshot(t.tag)
const d = derive(snap)
if (d.problems.length) throw new Error(`the snapshot does not fit:\n${d.problems.join('\n')}`)
const file = new URL(`../../src/locale/${t.tag}.ts`, import.meta.url)
writeFileSync(file, localeSource(t.tag, t.name, d, snap.meta.excel))
console.log(`${Object.keys(d.functions).length} functions (${d.unknown.length} unknown to this Excel: ${d.unknown.join(', ')}; ${d.dropped.length} not in books: ${d.dropped.join(', ')}) → ${file.pathname}`)
