/**
 * Writes the formula text of a locale file, `src/locales/<tag>.ts`, from Excel's snapshot (`test/excel/locale/<tag>.json`):
 *
 *   npx tsx bench/locale/generate.ts ru-RU
 *
 * Only the part between the file's two marks is written: the separators, TRUE and FALSE, error literals and the function
 * names that differ from the English ones, as the constant `FORMULA_TEXT`. The rest of the file is written by hand, so a
 * new locale's file starts as a copy of another's. `test/locale-excel.test.ts` checks ru-RU's text against the snapshot.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { pathToFileURL } from 'node:url'
import { derive, loadSnapshot, type Derived } from './derive.js'

/** The marks around the generated part, each a line of its own. */
export const MARKS = ['// ---- formula text, generated by bench/locale/generate.ts: do not edit ----', '// ---- end of formula text ----'] as const

/** `key: 'value'` entries packed into lines of at most `width` characters. */
function pack(entries: [string, string][], indent: string, width = 120): string {
  const lines: string[] = []
  let line = ''
  for (const [k, v] of entries) {
    const item = `${/^[A-Z][A-Z0-9]*$/.test(k) ? k : `'${k}'`}: '${v}',`
    if (line && indent.length + line.length + 1 + item.length > width) {
      lines.push(indent + line)
      line = item
    } else line = line ? `${line} ${item}` : item
  }
  if (line) lines.push(indent + line)
  return lines.join('\n')
}

/** The generated part: the formula text the snapshot gives. */
export function formulaText(d: Derived, excel: string): string {
  const differ = Object.entries(d.functions).filter(([en, l]) => en !== l).sort(([a], [b]) => (a < b ? -1 : 1))
  const errors = Object.entries(d.errors).filter(([en, l]) => en !== l)
  const q = (s: string) => `'${s.replace(/\\/g, '\\\\').replace(/'/g, "\\'")}'`
  return `/** Excel ${excel} for Mac's own formula text; functions whose name is the English one are not listed. */
const FORMULA_TEXT = {
  decimalSeparator: ${q(d.decimalSeparator)},
  listSeparator: ${q(d.listSeparator)},
  arrayColumnSeparator: ${q(d.arrayColumnSeparator)},
  arrayRowSeparator: ${q(d.arrayRowSeparator)},
  booleans: { TRUE: ${q(d.booleans.TRUE)}, FALSE: ${q(d.booleans.FALSE)} },
  errors: {
${pack(errors, '    ')}
  },
  functions: {
${pack(differ, '    ')}
  },
}`
}

/** `source` with the lines between its marks replaced by `part`; an error if the marks are not there once each, in order. */
export function withPart(source: string, part: string): string {
  const lines = source.split('\n')
  const [begin, end] = MARKS.map((m) => lines.indexOf(m))
  if (begin < 0 || end < begin || MARKS.some((m) => lines.lastIndexOf(m) !== lines.indexOf(m))) throw new Error(`the file needs the marks, once each:\n${MARKS.join('\n')}`)
  return [...lines.slice(0, begin + 1), part, ...lines.slice(end)].join('\n')
}

if (import.meta.url === pathToFileURL(process.argv[1]).href) {
  const tag = process.argv[2]
  if (!tag) throw new Error('usage: npx tsx bench/locale/generate.ts <tag>, such as ru-RU')
  const snap = loadSnapshot(tag)
  const d = derive(snap)
  if (d.problems.length) throw new Error(`the snapshot does not fit:\n${d.problems.join('\n')}`)
  const file = new URL(`../../src/locales/${tag}.ts`, import.meta.url)
  writeFileSync(file, withPart(readFileSync(file, 'utf8'), formulaText(d, snap.meta.excel)))
  console.log(`${Object.keys(d.functions).length} functions (${d.unknown.length} unknown to this Excel: ${d.unknown.join(', ')}; ${d.dropped.length} not in books: ${d.dropped.join(', ')}) → ${file.pathname}`)
}
